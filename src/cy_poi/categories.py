"""POI tag mapping shared with SurvivalAI Explore categories."""

def category(tags: dict[str, str]) -> str | None:
    amenity, healthcare, shop, leisure = (tags.get(k, "") for k in ("amenity", "healthcare", "shop", "leisure"))
    if amenity == "shelter" or tags.get("social_facility") == "shelter": return "shelter"
    if amenity == "hospital" or healthcare == "hospital": return "hospital"
    if amenity in {"clinic", "doctors"} or healthcare in {"clinic", "doctor"}: return "clinic"
    if amenity == "pharmacy" or healthcare == "pharmacy": return "pharmacy"
    if amenity == "police": return "police"
    if amenity == "fire_station": return "fire_station"
    if amenity == "drinking_water" or tags.get("natural") == "spring" or tags.get("man_made") == "water_well": return "water"
    if amenity == "fuel": return "fuel"
    if amenity == "toilets": return "toilets"
    if amenity == "school": return "school"
    if amenity == "place_of_worship": return "place_of_worship"
    if amenity == "atm": return "atm"
    if amenity == "bank": return "bank"
    if amenity == "parking": return "parking"
    if amenity == "charging_station": return "ev_charging"
    if amenity in {"restaurant", "fast_food"}: return "restaurant"
    if amenity == "cafe": return "cafe"
    if amenity in {"bus_station", "ferry_terminal"} or tags.get("public_transport") in {"station", "platform"} or tags.get("highway") == "bus_stop": return "transit"
    if amenity == "post_office": return "post_office"
    if leisure in {"stadium", "sports_centre", "pitch"}: return "sport"
    if shop == "supermarket": return "supermarket"
    if shop == "convenience": return "convenience"
    if shop == "greengrocer": return "grocery"
    if shop == "bakery": return "bakery"
    if amenity == "food_court": return "food"
    return None
